"""Wokwi export (phase 2): a design as Wokwi's `diagram.json`, with a `wokwi.toml` that
points the simulator at the PlatformIO build of the board's firmware.

Format: https://docs.wokwi.com/diagram-format. Each placement whose part has a
`wokwi_type` becomes a Wokwi part at its canvas position; each wire between two of them
becomes a connection in its colour. Parts without a type are left out, with their wires,
and listed so the user knows what the simulation lacks.
"""

import json
from dataclasses import dataclass, field

from app.modules.designs.models import Design, Placement
from app.modules.parts.models import PartKind, Pin, PinKind, Platform

DIAGRAM = "diagram.json"
TOML = "wokwi.toml"
# Wokwi draws parts at about their real size, far smaller than the app's cards, so the
# canvas positions are scaled down to keep the layout without big gaps.
SCALE = 0.5


@dataclass
class Skipped:
    ref: str
    part: str
    wires: int = 0


@dataclass
class Export:
    diagram: str
    toml: str | None
    # The board the toml runs, if any.
    board: Placement | None
    skipped: list[Skipped] = field(default_factory=list)


def wokwi_pin(placement: Placement, pin: Pin) -> str:
    """Wokwi's name for a pin: its `wokwi_name`; else, on a board, its code name (Wokwi
    calls the ESP32-C3's GPIO4 `4` and the Uno's D13 `13`); else the pin's own name."""
    if pin.wokwi_name:
        return pin.wokwi_name
    if placement.part.kind == PartKind.BOARD and (code := pin.effective_code_name):
        return code
    return pin.name


def _serial_monitor(board: Placement) -> list[list]:
    """ESP32 boards in Wokwi show Serial only when its pins are wired to the monitor."""
    if board.part.platform != Platform.ESP32:
        return []
    pins = board.part.pins
    tx = next((p for p in pins if p.kind == PinKind.UART_TX), None)
    rx = next((p for p in pins if p.kind == PinKind.UART_RX), None)
    connections = []
    if tx:
        connections.append([f"{board.ref}:{wokwi_pin(board, tx)}", "$serialMonitor:RX", "", []])
    if rx:
        connections.append([f"{board.ref}:{wokwi_pin(board, rx)}", "$serialMonitor:TX", "", []])
    return connections


def _toml(board: Placement) -> str:
    """wokwi.toml for the VS Code extension and wokwi-cli, pointing at the build of the
    board's `[env:<ref>]` in the generated platformio.ini."""
    image = "firmware.hex" if board.part.platform == Platform.AVR else "firmware.bin"
    build = f".pio/build/{board.ref}"
    return "\n".join(
        [
            f"# Wokwi simulation of {board.ref} ({board.part.name}), generated by Ohm Sweet Ohm.",
            "# Build first with `pio run`; the paths match the platformio.ini env.",
            "[wokwi]",
            "version = 1",
            f"firmware = '{build}/{image}'",
            f"elf = '{build}/firmware.elf'",
            "",
        ]
    )


def export(design: Design, board: Placement | None) -> Export:
    included = {p.id for p in design.placements if p.part.wokwi_type}
    parts = []
    skipped: dict[int, Skipped] = {}
    for placement in sorted(design.placements, key=lambda p: p.ref):
        part = placement.part
        if placement.id not in included:
            skipped[placement.id] = Skipped(placement.ref, part.name)
            continue
        entry: dict = {
            "type": part.wokwi_type,
            "id": placement.ref,
            "top": round(placement.y * SCALE),
            "left": round(placement.x * SCALE),
            "attrs": {},
        }
        if placement.rotation:
            entry["rotate"] = placement.rotation
        parts.append(entry)

    connections: list[list] = []
    if board is not None and board.id in included:
        connections += _serial_monitor(board)
    for wire in design.wires:
        ends = ((wire.a_placement, wire.a_pin), (wire.b_placement, wire.b_pin))
        missing = [p for p, _ in ends if p.id not in included]
        for placement in {p.id: p for p in missing}.values():
            skipped[placement.id].wires += 1
        if missing:
            continue
        a, b = (f"{p.ref}:{wokwi_pin(p, pin)}" for p, pin in ends)
        connections.append([a, b, str(wire.color), []])

    diagram = {
        "version": 1,
        "author": "Ohm Sweet Ohm",
        "editor": "wokwi",
        "parts": parts,
        "connections": connections,
        "dependencies": {},
    }
    toml = _toml(board) if board is not None and board.part.wokwi_type else None
    return Export(
        diagram=json.dumps(diagram, indent=2) + "\n",
        toml=toml,
        board=board,
        skipped=sorted(skipped.values(), key=lambda s: s.ref),
    )
