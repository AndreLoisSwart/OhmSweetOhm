"""The PlatformIO project file (build step 12): the board's platform and board id, and
the libraries the design's parts need on that platform, as `platformio.ini`."""

from dataclasses import dataclass, field

from app.modules.designs.models import Design, Placement
from app.modules.firmware.pinmap import choose_board
from app.modules.parts.models import PartKind, Platform

FILENAME = "platformio.ini"
# Boards whose Serial can run over the chip's own USB port, which needs a build flag.
NATIVE_USB_HINTS = ("c3", "c6", "s2", "s3", "h2")


@dataclass
class Libraries:
    """The design's libraries for one platform, each with the parts that need it."""

    used: dict[str, list[str]] = field(default_factory=dict)  # spec → refs
    # Libraries limited to other platforms, or to platforms when the board's is unknown.
    elsewhere: dict[str, list[str]] = field(default_factory=dict)


def libraries_for(design: Design, board: Placement) -> Libraries:
    platform = board.part.platform
    found = Libraries()
    seen: dict[str, str] = {}  # lower-case spec → spec as first written
    for placement in sorted(design.placements, key=lambda p: p.ref):
        part = placement.part
        # Another board in the design runs its own firmware.
        if part.kind == PartKind.BOARD and placement is not board:
            continue
        for library in part.libraries:
            spec = seen.setdefault(library["spec"].lower(), library["spec"])
            platforms = library.get("platforms") or []
            applies = not platforms or (platform is not None and platform in platforms)
            target = found.used if applies else found.elsewhere
            refs = target.setdefault(spec, [])
            if placement.ref not in refs:
                refs.append(placement.ref)
    return found


def library_name(spec: str) -> str:
    """The name as the Arduino IDE's Library Manager lists it: no owner, no version."""
    return spec.split("@", 1)[0].split("/", 1)[-1].strip()


def render(design: Design, board_ref: str | None = None) -> tuple[Placement, str]:
    board = choose_board(design, board_ref)
    part = board.part
    libraries = libraries_for(design, board)
    lines = [
        f"; PlatformIO project for {design.name} on {board.ref} ({part.name}).",
        "; Generated by Ohm Sweet Ohm from the design's parts. Library versions are the",
        "; parts' own; check them against the code you write.",
    ]
    if libraries.used:
        lines += ["", "; Libraries, and the parts that need them:"]
        lines += [f";   {spec}: {', '.join(refs)}" for spec, refs in libraries.used.items()]
        names = ", ".join(library_name(spec) for spec in libraries.used)
        lines += ["; Arduino IDE instead: install these from the Library Manager:", f";   {names}"]
    missing = [
        label
        for label, value in (
            ("platform", part.platform),
            ("PlatformIO board", part.platformio_board),
        )
        if value is None
    ]
    if missing:
        lines += [
            "",
            f"; {part.name} has no {' or '.join(missing)} yet: set it on the part's page,",
            "; or fill in the lines below by hand.",
        ]

    lines += ["", f"[env:{board.ref}]"]
    lines.append(f"platform = {part.platform}" if part.platform else "platform =")
    lines.append(f"board = {part.platformio_board}" if part.platformio_board else "board =")
    lines += ["framework = arduino", "monitor_speed = 115200"]
    board_id = (part.platformio_board or "").lower()
    if part.platform == Platform.ESP32 and any(hint in board_id for hint in NATIVE_USB_HINTS):
        lines += [
            "; Uncomment to send Serial over the chip's own USB port (boards like the",
            "; ESP32-C3 SuperMini have no separate USB-serial chip):",
            "; build_flags = -D ARDUINO_USB_CDC_ON_BOOT=1",
        ]
    if libraries.used:
        lines.append("lib_deps =")
        lines += [f"    {spec}" for spec in libraries.used]
    if libraries.elsewhere:
        where = f"on {part.platform}" if part.platform else "until the board's platform is set"
        lines += ["", f"; Not used {where} (they're for other platforms):"]
        lines += [f";   {spec}: {', '.join(refs)}" for spec, refs in libraries.elsewhere.items()]
    return board, "\n".join(lines) + "\n"
